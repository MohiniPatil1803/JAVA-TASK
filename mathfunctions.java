public class mathfunctions {
    public static void main(String[] args) {
        int a=40,b=30;

        System.out.println("Maximum number is: "+Math.max(a,b));
        System.out.println("Maximum number is: "+Math.min(a,b));
        System.out.println("Square root is: "+Math.sqrt(64));
        System.out.println("Power is: "+Math.pow(3,9));
        System.out.println("Absolute Value is: "+Math.abs(-47));
        System.out.println(Math.random());

        System.out.println("Downwards of number is : "+Math.floor(7.8));
        System.out.println("Upwards of number is: "+Math.ceil(9.8));
        System.out.println("Rounded Number is : "+Math.round(3.3));
    }
}
